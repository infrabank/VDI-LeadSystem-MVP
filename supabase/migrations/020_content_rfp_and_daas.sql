## 10. 자주 받는 질문

### Q1. "본 RFP 문구를 그대로 사용해도 되나?"

*안 된다*. 기관 환경·예산·일정·법무 검토에 따라 조정. 본 글은 *초안 가이드*이지 정식 RFP가 아니다.

### Q2. "RFP 사양이 너무 많으면 입찰사가 부담스러워하지 않나?"

부담스러워하는 입찰사는 사양 정확성이 *부족*한 곳이다. 명확한 RFP는 정확한 입찰사를 끌어들인다.

### Q3. "기관 보안 부서가 사양 작성 경험이 부족한데?"

[보안성 검토 대응 체크리스트 PDF](/insights/security-review-response-checklist)에 RFP 반영 문구 4종 예시가 추가로 있다. 본 글의 사양과 함께 활용.

### Q4. "1인+파트너 컨소시엄 구조를 우대 항목으로 두는 게 합리적인가?"

기관 정책에 따른다. 마이로켓 입장에서는 *책임 분담 명확성*을 평가 기준에 두면 1인 회사·중소 SI도 공정 평가 가능하다는 입장.

