## 9. 자주 받는 질문 5가지

### Q1. "AVD vs Citrix DaaS vs Windows 365 어느 게 좋나?"

*기관 환경에 따라 다르다*. M365 도입 기관은 AVD·Windows 365가 자연스럽다. Citrix 운영 경험이 풍부한 기관은 Citrix DaaS가 마이그레이션 부담 적다. 단순 사용자(O 등급)는 Windows 365의 단순성이 매력.

### Q2. "DaaS로 옮기면 라이선스 비용이 줄어드는가?"

*초기 5년 TCO는 비슷하거나 더 높을 수 있다*. 하드웨어·전력 비용 감소 + DaaS 라이선스·클라우드 비용 증가. 단, 운영 인력·갱신 부담은 줄어든다. 5년 TCO를 정확히 산정.

### Q3. "C 등급도 DaaS로 옮길 수 있나?"

*가능하지만 신중히*. 데이터 위치·공동책임 매트릭스·격리 통제·감사 로그 5가지를 충족하면 가능. 통상 *온프레 VDI 유지*가 안전한 결정.

### Q4. "DaaS 운영자가 부족한데 어떻게 시작?"

*소규모 PoC*부터 시작. O·일반 S 등급 ~50명 규모 PoC → 6~12개월 운영 후 확대 결정.

### Q5. "DaaS는 N²SF 위원회 통과가 어렵나?"

*반드시 어렵지는 않다*. CSAP 인증·데이터 위치·공동책임 매트릭스·운영 절차가 *문서화*되면 통과 가능. 위원회는 *근거 자료*를 본다.

