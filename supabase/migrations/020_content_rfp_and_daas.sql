## 1. 왜 이 질문이 자주 나오는가

DaaS(Citrix DaaS·Azure Virtual Desktop·Windows 365)는 다음과 같은 매력이 있다.

- 인프라·하이퍼바이저 EOS 부담 없음
- 사용자 수 증감에 따른 라이선스 유연성
- 클라우드 이전을 통한 *N²SF 정렬 자동화* 기대
- 운영 인력 부담 감소

그래서 다음 가정이 흔히 나온다.

> "DaaS로 옮기면 N²SF 등급 통제도 자동으로 만족되고, 운영 부담도 줄어든다."

이 가정은 *부분적*이다. 5가지 검토를 통과해야 한다.

---

## 2. 검토 1 — CSAP 인증

공공기관 도입 클라우드는 **CSAP(Cloud Security Assurance Program) 인증**이 필요하다.

- IaaS CSAP 인증: 클라우드 인프라 도입 시
- SaaS CSAP 인증: SaaS 형태 DaaS 도입 시 (별도)

**현재 시장 (2026년 시점)**:
- Azure Korea: IaaS CSAP 인증 보유
- AWS Korea: 일부 인증 보유
- Naver Cloud Platform: 일부 인증 보유
- Google Cloud Korea: 일부 인증 보유

**유의 사항**: DaaS 자체보다 *DaaS가 올라가는 클라우드 인프라*의 인증을 본다. AVD를 Azure Korea에서 운영하면 IaaS CSAP가 활용된다.

---

## 3. 검토 2 — 데이터 위치 (Data Residency)

N²SF 등급별로 데이터가 *어디에 저장되는지* 확인.

| 등급 | 데이터 위치 요건 | DaaS 적합성 |
|---|---|---|
| C(기밀) | 한국 내 + 기관 통제 영역 | 일반적으로 *온프레 VDI 유지*. DaaS 적용 시 별도 통제·격리 필요 |
| S(민감) | 한국 내 (CSAP 인증 클라우드) | *부분 전환* 가능. 데이터 위치 명시 + 백업 체계 검토 |
| O(공개) | 한국 또는 글로벌 (정책에 따라) | DaaS 적합 |

**유의 사항**: 같은 시스템이라도 데이터 일부가 C·S·O로 혼재된다. 등급별로 분리해 *영역별 결정*.

---

## 4. 검토 3 — 공동책임 모델 (Shared Responsibility)

CSP(Cloud Service Provider)·DaaS 벤더·기관(테넌트)의 *책임 매트릭스*를 명확히 한다.

| 항목 | CSP 책임 | DaaS 벤더 책임 | 기관(테넌트) 책임 |
|---|---|---|---|
| 인프라(전력·냉각·물리 보안) | ✓ | — | — |
| 호스트 OS·하이퍼바이저 | ✓ | — | — |
| DaaS 컨트롤 플레인 | — | ✓ | — |
| 게스트 OS | — | 일부 | ✓ |
| 사용자 데이터·앱 | — | — | ✓ |
| 사용자 인증·접근 정책 | — | 일부 | ✓ |
| 백업·DR | — | 일부 | ✓ |
| 보안 모니터링·감사 | — | 일부 | ✓ |

**유의 사항**: 위 매트릭스를 *문서화* 안 하면 사고 시 책임 떠넘기기 발생. 보안성 검토 대응표에 매트릭스를 첨부.

---

## 5. 검토 4 — 운영 인력 변화

온프레 VDI 운영자와 DaaS 운영자는 *다른 역할*이다.

| 영역 | 온프레 VDI | DaaS |
|---|---|---|
| 인프라 | 호스트·스토리지·네트워크 운영 | 클라우드 인프라 모니터링·계정 관리 |
| 컨트롤 플레인 | 직접 운영 | 벤더 책임 (모니터링만) |
| 사용자 환경 | 직접 구성 | 이미지·정책으로 표준화 |
| 비용 관리 | 라이선스·하드웨어 | 클라우드 비용·라이선스 모니터링 |
| 장애 대응 | 직접 분석·복구 | 1차 진단 후 벤더 협조 |

**유의 사항**: 운영자 *재교육* 또는 *추가 채용* 필요. 비용 절감을 기대하고 DaaS 도입 후 운영자 부족으로 어려움 겪는 사례 흔함.

---

## 6. 검토 5 — 사용자 경험 (UX)

DaaS는 네트워크 의존성이 높다. 다음을 검토.

- **로그인 시간**: 온프레 < DaaS (네트워크 지연·이미지 로드 + 라이선스 검증)
- **로컬 도구 호환성**: 일부 도구는 DaaS 환경에서 제한
- **인쇄·USB·로컬 스토리지**: 정책 변경 필요
- **다중 모니터·해상도**: 네트워크·프로토콜에 따라 차이
- **오프라인 작업**: DaaS는 인터넷 필요

**유의 사항**: 사용자 교육·매뉴얼 갱신을 사업 일정에 포함. 미반영 시 사용자 불만으로 사업 평가 하락.

