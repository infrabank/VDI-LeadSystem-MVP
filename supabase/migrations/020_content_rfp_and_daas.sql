## 7. 영역별 권장 — DaaS 적합도 매트릭스

기관 환경에 따라 다르지만 일반적인 가이드:

| 영역 | DaaS 적합도 | 권장 |
|---|---|---|
| O 등급 인터넷 업무 | 높음 | DaaS 또는 SaaS 대체 |
| O·S 등급 일반 사무 | 중간 | DaaS 부분 전환 검토 |
| S 등급 핵심 업무 | 중간~낮음 | 데이터 위치·공동책임 확인 후 영역별 |
| C 등급 핵심 업무 | 낮음 | 온프레 VDI 유지 권장 |
| 외부 협력사 단기 접근 | 중간 | DaaS + Zero Trust 조합 |
| 고위험·세션 격리 필요 | 낮음 | 온프레 VDI + 강화 통제 |

