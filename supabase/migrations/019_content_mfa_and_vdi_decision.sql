### Q1. "이 체크리스트 결과를 외부 자문 없이 발주 자료로 쓸 수 있나?"

내부 회의·임원 보고에는 그대로 사용 가능. 정식 발주 RFP·보안성 검토 산출물은 *별도 작성*이 필요.

### Q2. "❓가 많은데 정상인가?"

흔하다. ❓는 *추가 인터뷰·자료 회수가 필요한 영역*이라는 신호. 5개 이상이면 외부 1차 진단을 권장.

### Q3. "8영역 모두 채워야 하나?"

본인 기관에 해당하는 영역만. 외부접속 운영 안 하는 기관은 §3 생략 가능.

### Q4. "PDF 다운로드 버전이 있나?"

