## 7. 그래서 어떻게 결정할 것인가

순서는 다음과 같다.

1. **현황 파악** — 기존 VDI/망분리/MFA/백업 환경 자가 점검 (1주 내)
2. **C/S/O 예비 분류** — 핵심 업무 10~20개부터
3. **영역별 시나리오 1차 매핑** — 위 표 참고
4. **운영 리스크 평가** — 라이선스·EOS·인증서·인력
5. **시나리오 결정문 작성** — 5문장 결정 + 영역별 결정 표
6. **RFP 반영 문구 초안** — 발주 전 사양 정리

